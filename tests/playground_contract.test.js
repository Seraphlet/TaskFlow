const assert = require('assert');
const fs = require('fs');

const index = fs.readFileSync('index.html', 'utf8');
const app = fs.readFileSync('js/app.js', 'utf8');
const music = fs.readFileSync('js/playground/music-geometry.js', 'utf8');
const keyboard = fs.readFileSync('js/playground/keyboard-art.js', 'utf8');
const life = fs.readFileSync('js/playground/life-geometry.js', 'utf8');
const styles = fs.readFileSync('styles.css', 'utf8');

assert.strictEqual(index.includes('music-geometry.js'), false, 'music module must not be statically loaded');
assert.strictEqual(index.includes('keyboard-art.js'), false, 'keyboard module must not be statically loaded');
assert.strictEqual(index.includes('life-geometry.js'), false, 'life module must not be statically loaded');
assert.match(app, /import\(modulePath\)/, 'artwork modules must use dynamic import()');
assert.match(app, /artworkLoadToken/, 'dynamic loads must be protected against stale completion');
assert.match(app, /destroyActiveArtwork\(\)/, 'render boundaries must destroy the previous artwork');

for (const [name, source] of [['music', music], ['keyboard', keyboard], ['life', life]]) {
  assert.match(source, /export function createArtwork\(container\)/, `${name} must export createArtwork`);
  assert.match(source, /\bstart\b/, `${name} must expose start`);
  assert.match(source, /\bpause\b/, `${name} must expose pause`);
  assert.match(source, /\bdestroy\b/, `${name} must expose destroy`);
  assert.match(source, /cancelAnimationFrame/, `${name} must cancel animation frames`);
  assert.match(source, /ResizeObserver/, `${name} must manage canvas resize`);
  assert.match(source, /visibilitychange/, `${name} must react to tab visibility`);
  if (name !== 'life') assert.doesNotMatch(source, /from\s+['"]|require\(/, `${name} must not introduce runtime dependencies`);
}

assert.match(music, /new AudioContextClass\(\)/, 'AudioContext must be created lazily in the artwork module');
assert.match(music, /URL\.createObjectURL\(file\)/, 'local audio must stay in the browser');
assert.match(music, /navigator\.mediaDevices\.getDisplayMedia/, 'music artwork must request user-approved tab capture');
assert.match(music, /getAudioTracks\(\)\[0\]/, 'music artwork must reject streams without shared audio');
assert.match(music, /captureAudioTrack\.addEventListener\('ended'/, 'music artwork must track browser-ended capture');
assert.match(music, /createMediaStreamSource\(stream\)/, 'captured audio must feed Web Audio analysis');
assert.match(music, /connectAnalysisSource\(audioContext\.createMediaStreamSource\(stream\),\s*false\)/, 'capture analysis must not output duplicate audio');
assert.match(music, /captureStream\.getTracks\(\)\.forEach\(\(track\)\s*=>\s*track\.stop\(\)\)/, 'capture tracks must stop during cleanup');
assert.match(music, /analyser\.fftSize=1024/, 'music analysis must use the intended low-cost FFT size');
assert.match(music, /ANALYSIS_INTERVAL_MS = 40/, 'audio features must update independently near 25 Hz');
assert.match(music, /phase:'entering'/, 'companion lines must enter through an explicit lifecycle');
assert.match(music, /line\.phase='leaving'/, 'companion lines must leave through an explicit lifecycle');
assert.match(music, /MAX_COMPANIONS = 3/, 'music must cap dynamic companion ribbons at three');
assert.match(music, /timer\.activeMs>=900/, 'single-frame changes must not create companion ribbons');
assert.match(music, /timer\.inactiveMs>=2200/, 'stable layers must not disappear when the baseline adapts');
assert.match(music, /mode==='rest'/, 'ended input must enter a tail-decay state');
assert.match(music, /novelty=Math\.max\(0,value-baseline\)/, 'new layers must be compared with a stable recent baseline');
assert.match(music, /function drawRibbon/, 'each logical layer must render as a bundle of nearby fine lines');
assert.match(music, /organicMain/, 'main ribbon must use organic compound motion');
assert.match(music, /worldX-area\.span\*\.5/, 'music viewport must follow continuously once the head reaches the middle');
assert.match(music, /livePoint=\{x:worldX/, 'music head must interpolate every animation frame rather than wait for samples');
assert.match(music, /data-perf/, 'music artwork must expose lightweight measured frame timing');
assert.strictEqual((music.match(/const beatLine=/g) || []).length, 1, 'music must add exactly one independent beat line');
assert.match(music, /estimateBeatPeriod/, 'beat line must use a period estimator rather than onset density as BPM');
assert.match(music, /beatPhase/, 'beat line must track an independently estimated phase');
assert.doesNotMatch(music, /area\.bottom-area-top/, 'companion coordinates must not contain the invalid height expression');
assert.match(keyboard, /const KEYS = \['A', 'S', 'D', 'F', 'G', 'H', 'J', 'K'\]/, 'keyboard mapping must expose A-K effects');
assert.match(keyboard, /MAX_MARKS = 900/, 'keyboard artwork must cap visual entities');
assert.match(keyboard, /while \(voices\.length >= 8\)/, 'keyboard audio must cap overlapping voices');
assert.match(keyboard, /createDynamicsCompressor/, 'keyboard audio must protect against sudden volume spikes');
assert.match(keyboard, /data-mute/, 'keyboard artwork must provide mute control');
assert.match(keyboard, /data-volume/, 'keyboard artwork must provide volume control');
assert.match(keyboard, /input, textarea, select/, 'keyboard artwork must ignore text inputs');
assert.match(life, /simulateLife\(templateSnapshot,world/, 'life artwork must render simulation results instead of deciding events in Canvas');
assert.match(life, /playhead\*pixelsPerTime-available\*\.5/, 'life viewport must keep the current time near the middle');
assert.match(life, /data-life-duration/, 'life artwork must offer the requested 60-180 second viewing range');
assert.match(life, /result\.endAge\/effectiveDuration/, 'life pacing must use selected viewing duration instead of raw lifespan speed');
assert.match(life, /async function precomputePlayback/, 'life paths and event nodes must be prepared before playback');
assert.match(life, /new Float32Array/, 'life playback must cache compact sampled coordinates');
assert.match(life, /prepareWhenIdle/, 'next-life preparation must yield to transition rendering');
assert.match(life, /lowerBound\(track\.times,firstVisibleTime\)/, 'life rendering must begin at the visible sample range');
assert.match(life, /pendingPreparation\?\.status==='ready'/, 'life transitions must wait for a complete prepared result');
assert.match(life, /preparationToken\+=1/, 'setting changes and destroy must invalidate stale prepared lives');
assert.match(life, /provider\.generateLife/, 'AI life generation must reuse the existing Radar provider');
assert.match(life, /preparedNode\.centered/, 'event nodes must use the same centered relationship position as their curve');
const lifeDraw = life.slice(life.indexOf('function draw(){'), life.indexOf('function effectiveDuration'));
assert.doesNotMatch(lifeDraw, /stateOffset\(|interpolate\(/, 'life draw loop must not repeat state interpolation');
assert.match(life, /new Audio\(\)/, 'life artwork must provide independent local background audio');
assert.doesNotMatch(life, /AnalyserNode|createAnalyser/, 'life background music must not affect simulation or curves');
assert.match(styles, /\.playground-shell > \.sidebar \{ position: sticky;/, 'desktop playground sidebar must remain fixed within the viewport');
assert.match(styles, /\.life-event-feed b \{ font-size: 13px; \}/, 'life event summaries must remain readable');
assert.match(styles, /\.life-event-feed small \{[^}]*font-size: 12px;/, 'life event metadata must remain readable');

console.log('Playground lifecycle and cold-start contract tests passed');
